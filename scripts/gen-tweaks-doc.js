// Generates docs/TWEAKS.md from the catalog. Run with `npm run docs`.
// CI fails if the committed file is out of date (see .github/workflows/ci.yml).
const fs = require('fs');
const path = require('path');
const { TWEAKS, CATEGORIES, PRESETS } = require('../src/main/tweaks');
const { BOOSTS } = require('../src/main/boosts');

const risk = { safe: '🟢 safe', medium: '🟡 medium', high: '🔴 high' };
const esc = (s) => s.replace(/\|/g, '\\|');
const lines = [];
lines.push('# Tweak catalog', '');
lines.push(`<!-- Generated by scripts/gen-tweaks-doc.js. Do not edit by hand. -->`, '');
lines.push(`Event Horizon ships **${TWEAKS.length} tweaks** in ${Object.keys(CATEGORIES).length} categories and **${BOOSTS.length} boost-ups**.`, '');
lines.push('Every tweak has three PowerShell scripts in [`src/main/tweaks.js`](../src/main/tweaks.js):', '');
lines.push('- **apply** makes the change.');
lines.push('- **revert** restores the Windows default value (not necessarily the value you had before, see [Rollback](../README.md#rollback)).');
lines.push('- **check** reads the live state, which is what the toggle in the app shows.', '');
lines.push('Legend: ⟳ needs a reboot · ★ recommended · 👤 runs without administrator rights', '');
lines.push('## Presets', '');
lines.push('| Preset | Tweaks | What it includes |', '|---|---|---|');
for (const [, p] of Object.entries(PRESETS)) lines.push(`| ${p.name} | ${TWEAKS.filter(p.filter).length} | ${esc(p.blurb)} |`);
lines.push('');
for (const [key, c] of Object.entries(CATEGORIES)) {
  const list = TWEAKS.filter(t => t.cat === key);
  lines.push(`## ${c.name} (${list.length})`, '', `${c.blurb}`, '');
  lines.push('| Tweak | Risk | Notes | What it does |', '|---|---|---|---|');
  for (const t of list) {
    const notes = [t.reboot && '⟳', t.recommended && '★', t.userScope && '👤', t.requires === 'nvidia' && 'NVIDIA only'].filter(Boolean).join(' ');
    lines.push(`| **${esc(t.name)}**<br><sub>\`${t.id}\`</sub> | ${risk[t.risk]} | ${notes} | ${esc(t.desc)} |`);
  }
  lines.push('');
}
lines.push('## Boost-ups', '', 'One-shot maintenance actions. These are not reversible toggles.', '');
lines.push('| Boost-up | Category | What it does |', '|---|---|---|');
for (const b of BOOSTS) lines.push(`| **${esc(b.name)}**<br><sub>\`${b.id}\`</sub> | ${b.cat} | ${esc(b.desc)} |`);
lines.push('');

const out = path.join(__dirname, '..', 'docs', 'TWEAKS.md');
fs.mkdirSync(path.dirname(out), { recursive: true });
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur.replace(/\r\n/g, '\n') !== text) { console.error('docs/TWEAKS.md is out of date. Run `npm run docs`.'); process.exit(1); }
  console.log('docs/TWEAKS.md is up to date.');
} else {
  fs.writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
